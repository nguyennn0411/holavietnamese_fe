export const PLACEMENT_OPTION_TRANSLATIONS = {};

/**
 * Retrieves the properly localized option text for a question, preventing mixed languages.
 * @param {Object} question - The placement test question
 * @param {string} option - Current option string
 * @param {number} optIndex - Index of option in array
 * @param {string} lang - 'en' | 'vi'
 */
export function getLocalizedOptionForQuestion(question, option, optIndex = 0, lang = 'en') {
  if (!option) return '';
  if (typeof option === 'object') {
    return lang === 'vi' ? (option.vi || option.en) : (option.en || option.vi);
  }

  const targetLang = (lang || 'en').toLowerCase();

  // 1. Precise question-level mapping (guarantees all 4 options match target language)
  if (question?.id && QUESTION_EXPLANATION_MAP[question.id]) {
    const qData = QUESTION_EXPLANATION_MAP[question.id];
    const viIdx = qData.vi.indexOf(option);
    if (viIdx !== -1) {
      return targetLang === 'en' ? qData.en[viIdx] : qData.vi[viIdx];
    }
    const enIdx = qData.en.indexOf(option);
    if (enIdx !== -1) {
      return targetLang === 'vi' ? qData.vi[enIdx] : qData.en[enIdx];
    }
    if (typeof optIndex === 'number' && optIndex >= 0 && optIndex < qData.en.length) {
      return targetLang === 'en' ? qData.en[optIndex] : qData.vi[optIndex];
    }
  }

  // 2. Global fallback search across QUESTION_EXPLANATION_MAP (for callers not passing question)
  for (const qId in QUESTION_EXPLANATION_MAP) {
    const qData = QUESTION_EXPLANATION_MAP[qId];
    const viIdx = qData.vi.indexOf(option);
    if (viIdx !== -1) {
      return targetLang === 'en' ? qData.en[viIdx] : qData.vi[viIdx];
    }
    const enIdx = qData.en.indexOf(option);
    if (enIdx !== -1) {
      return targetLang === 'vi' ? qData.vi[enIdx] : qData.en[enIdx];
    }
  }

  return option;
}

export function getLocalizedOption(option, lang = 'en', question = null, optIndex = 0) {
  return getLocalizedOptionForQuestion(question, option, optIndex, lang);
}

export function areOptionsMatching(sel, opt, question = null) {
  if (!sel || !opt) return false;
  if (sel === opt) return true;
  if (question?.id && QUESTION_EXPLANATION_MAP[question.id]) {
    const qData = QUESTION_EXPLANATION_MAP[question.id];
    const selViIdx = qData.vi.indexOf(sel) !== -1 ? qData.vi.indexOf(sel) : qData.en.indexOf(sel);
    const optViIdx = qData.vi.indexOf(opt) !== -1 ? qData.vi.indexOf(opt) : qData.en.indexOf(opt);
    if (selViIdx !== -1 && selViIdx === optViIdx) return true;
  }
  return false;
}

export function isAnswerCorrect(response, question) {
  if (!response || !question) return false;
  if (response === question.answer || response === question.answerEn || response === question.answerVi) return true;
  if (typeof question.answer === 'object') {
    if (response === question.answer.en || response === question.answer.vi) return true;
  }

  // Question-level check
  if (question?.id && QUESTION_EXPLANATION_MAP[question.id]) {
    const qData = QUESTION_EXPLANATION_MAP[question.id];
    if (response === qData.answer || response === qData.answerEn) return true;
    const ansIdx = qData.vi.indexOf(qData.answer);
    if (ansIdx !== -1 && (response === qData.en[ansIdx] || response === qData.vi[ansIdx])) return true;
  }

  // Global search across QUESTION_EXPLANATION_MAP
  for (const qId in QUESTION_EXPLANATION_MAP) {
    const qData = QUESTION_EXPLANATION_MAP[qId];
    if (question.answer === qData.answer || question.answer === qData.answerEn) {
      if (response === qData.answer || response === qData.answerEn) return true;
    }
  }

  const rawAns = String(question.answer || '').trim();
  const rawResp = String(response || '').trim();
  if (rawAns === rawResp) return true;

  return false;
}
